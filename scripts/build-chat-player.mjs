// Builds the connector's chat pages (chat-player/) into lib/mcp/chat-player-html.ts:
//   - the exercise player (chat-player/main.ts + styles.css): one IIFE and its CSS inlined into two
//     full pages — CHAT_PLAYER_HTML (the MCP App resource) and CHAT_PLAYER_ARTIFACT (the standalone
//     artifact, with ARTIFACT_SET_SLOT for fillArtifact);
//   - the review page (chat-player/review-main.ts + review/review.css): CHAT_REVIEW_HTML, an MCP App
//     only («Уровни слов», «Новые слова», «Настроить упражнение», «Повторить слова»);
//   - the cards page (chat-player/cards-main.ts + cards/cards.css): CHAT_CARDS_HTML, an MCP App only
//     («Карточки в чате»: play_cards, grade_cards, undo_grades).
// All three share bridge.ts, dom.ts and base.css (pulled in by each stylesheet's @import). The output is
// committed, like public/lexique: the connector serves it without a build step. Run
// `npm run build:player` after changing chat-player/ or the rules it imports.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "lib/mcp/chat-player-html.ts");

// The contract's constants, from the TypeScript source itself (bundled to a module and imported).
const contract = await build({
  entryPoints: [path.join(root, "lib/core/chat-player.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
});
const { ARTIFACT_SET_SLOT, ARTIFACT_TITLE } = await import(`data:text/javascript;base64,${Buffer.from(contract.outputFiles[0].text).toString("base64")}`);

async function bundle(entry, stylesheet) {
  const script = await build({
    entryPoints: [path.join(root, entry)],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020", "safari15"],
    minify: true,
    charset: "utf8",
    legalComments: "none",
    tsconfig: path.join(root, "tsconfig.json"),
    write: false,
  });
  const styles = await build({
    entryPoints: [path.join(root, stylesheet)],
    bundle: true,
    minify: true,
    charset: "utf8",
    legalComments: "none",
    loader: { ".css": "css" },
    write: false,
  });
  const js = script.outputFiles[0].text.trim();
  const css = styles.outputFiles[0].text.trim();
  // Inline <script> / <style> end at the first closing tag, whatever the JS or CSS means by it.
  if (/<\/script/i.test(js) || /<!--/.test(js)) throw new Error(`${entry}: bundle contains </script or <!--`);
  if (/<\/style/i.test(css)) throw new Error(`${stylesheet}: CSS contains </style`);
  return { js, css };
}

const page = ({ js, css }, mode, title, head) =>
  `<!doctype html><html lang="ru" data-mode="${mode}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark"><title>${title}</title><style>${css}</style></head><body><div id="app"></div>${head}<script>${js}</script></body></html>`;

const player = await bundle("chat-player/main.ts", "chat-player/styles.css");
const html = page(player, "app", "Упражнение", "");
const artifact = page(player, "artifact", ARTIFACT_TITLE, `<script>window.KARTOCHKI_SET = ${ARTIFACT_SET_SLOT};</script>`);
if (artifact.split(ARTIFACT_SET_SLOT).length !== 2) throw new Error("the artifact template must hold the set slot exactly once");

const reviewBundle = await bundle("chat-player/review-main.ts", "chat-player/review/review.css");
const review = page(reviewBundle, "app", "Проверка", "");

const cardsBundle = await bundle("chat-player/cards-main.ts", "chat-player/cards/cards.css");
const cards = page(cardsBundle, "app", "Карточки", "");

const source = `// Generated by scripts/build-chat-player.mjs from chat-player/ — do not edit; run \`npm run build:player\`.
// The chat pages: the exercise player (lib/core/chat-player.ts) as two pages, the review page
// (lib/core/chat-review.ts) and the cards page (lib/core/chat-cards.ts).

/** The MCP App page: the connector's CHAT_PLAYER_URI resource (MCP_APP_MIME). */
export const CHAT_PLAYER_HTML = ${JSON.stringify(html)};

/** The standalone artifact: fillArtifact puts a set into its ARTIFACT_SET_SLOT. */
export const CHAT_PLAYER_ARTIFACT = ${JSON.stringify(artifact)};

/** The review page («Уровни слов», «Новые слова», «Настроить упражнение», «Повторить слова»): the connector's CHAT_REVIEW_URI resource (MCP_APP_MIME). */
export const CHAT_REVIEW_HTML = ${JSON.stringify(review)};

/** The cards page («Карточки в чате»): the connector's CHAT_CARDS_URI resource (MCP_APP_MIME). */
export const CHAT_CARDS_HTML = ${JSON.stringify(cards)};
`;
await writeFile(out, source);
const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`;
console.log(
  `chat player: js ${kb(player.js)}, css ${kb(player.css)}; CHAT_PLAYER_HTML ${kb(html)}, CHAT_PLAYER_ARTIFACT ${kb(artifact)}\n` +
    `chat review: js ${kb(reviewBundle.js)}, css ${kb(reviewBundle.css)}; CHAT_REVIEW_HTML ${kb(review)}\n` +
    `chat cards: js ${kb(cardsBundle.js)}, css ${kb(cardsBundle.css)}; CHAT_CARDS_HTML ${kb(cards)} → ${path.relative(root, out)}`,
);
