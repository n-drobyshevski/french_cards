// Builds the chat exercise player (chat-player/) into lib/mcp/chat-player-html.ts: one IIFE and
// its CSS inlined into two full pages — CHAT_PLAYER_HTML (the connector's MCP App resource) and
// CHAT_PLAYER_ARTIFACT (the standalone artifact, with ARTIFACT_SET_SLOT for fillArtifact). The
// output is committed, like public/lexique: the connector serves it without a build step. Run
// `npm run build:player` after changing chat-player/ or the rules it imports.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "lib/mcp/chat-player-html.ts");

// The contract's constants, from the TypeScript source itself (bundled to a module and imported).
const contract = await build({
  entryPoints: [path.join(root, "lib/core/chat-player.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
});
const { ARTIFACT_SET_SLOT, ARTIFACT_TITLE } = await import(`data:text/javascript;base64,${Buffer.from(contract.outputFiles[0].text).toString("base64")}`);

const script = await build({
  entryPoints: [path.join(root, "chat-player/main.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020", "safari15"],
  minify: true,
  charset: "utf8",
  legalComments: "none",
  tsconfig: path.join(root, "tsconfig.json"),
  write: false,
});
const js = script.outputFiles[0].text.trim();
const css = (await transform(await readFile(path.join(root, "chat-player/styles.css"), "utf8"), { loader: "css", minify: true, charset: "utf8" })).code.trim();

// Inline <script> / <style> end at the first closing tag, whatever the JS or CSS means by it.
if (/<\/script/i.test(js) || /<!--/.test(js)) throw new Error("player bundle contains </script or <!--");
if (/<\/style/i.test(css)) throw new Error("player CSS contains </style");

const page = (mode, title, head) =>
  `<!doctype html><html lang="ru" data-mode="${mode}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark"><title>${title}</title><style>${css}</style></head><body><div id="app"></div>${head}<script>${js}</script></body></html>`;

const html = page("app", "Упражнение", "");
const artifact = page("artifact", ARTIFACT_TITLE, `<script>window.KARTOCHKI_SET = ${ARTIFACT_SET_SLOT};</script>`);
if (artifact.split(ARTIFACT_SET_SLOT).length !== 2) throw new Error("the artifact template must hold the set slot exactly once");

const source = `// Generated by scripts/build-chat-player.mjs from chat-player/ — do not edit; run \`npm run build:player\`.
// The chat exercise player (lib/core/chat-player.ts): the same bundle as two pages.

/** The MCP App page: the connector's CHAT_PLAYER_URI resource (MCP_APP_MIME). */
export const CHAT_PLAYER_HTML = ${JSON.stringify(html)};

/** The standalone artifact: fillArtifact puts a set into its ARTIFACT_SET_SLOT. */
export const CHAT_PLAYER_ARTIFACT = ${JSON.stringify(artifact)};
`;
await writeFile(out, source);
const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`;
console.log(`chat player: js ${kb(js)}, css ${kb(css)}; CHAT_PLAYER_HTML ${kb(html)}, CHAT_PLAYER_ARTIFACT ${kb(artifact)} → ${path.relative(root, out)}`);
