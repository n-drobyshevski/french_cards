const bare = (part: string) => part.replace(/^-|-$/g, "").replace(/\d+$/, "");

/** The Russian gloss of «in-», «-able»…; null for a root or an affix we do not know. */
export function affixGloss(part: string): string | null {
  if (part.endsWith("-")) return PREFIXES[bare(part)] ?? null;
  if (part.startsWith("-")) return SUFFIXES[bare(part)] ?? null;
  return null;
}

export const isAffix = (part: string) => bare(part) in PREFIXES || bare(part) in SUFFIXES;
